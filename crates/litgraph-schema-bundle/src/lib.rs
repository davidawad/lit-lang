//! One JSON Schema (draft 2020-12) holding every document kind a non-Rust
//! binding needs: the litgraph request/response contract, packs, links,
//! scenarios, clock fragments, calibration sets, `validate` results, and the
//! litigate CLI envelope, in-memory run, `*.map.json` sidecar and
//! `litigate timeline` document (`litigate.timeline/1`).
//!
//! The root is an object whose properties are the kinds, each a `$ref` into
//! one shared `$defs`, so a type used by several kinds (a `Scenario` inside
//! both a request and a named scenario) is defined exactly once. Rust stays
//! the source of truth: `packages/litigate-ts` generates its TypeScript
//! types from this output (`just ts-gen`) and CI fails when they are stale.

use litigate_base::timeline::Timeline;
use litigate_base::{Envelope, LitigateRun};
use litigate_engine::api::{CalibrationSet, Request, Response, Validation};
use litigate_engine::clock::ClockLibrary;
use litigate_engine::model::{LinkFile, Pack};
use litigate_engine::scenario::{NamedScenario, Scenario};
use litigate_lower::source_map::SourceMap;
use schemars::{JsonSchema, SchemaGenerator};
use serde_json::{json, Map, Value};

/// A kind: its bundle key, the `$defs` name it is published under, and
/// how to register its root type.
struct Kind {
    key: &'static str,
    name: &'static str,
    register: fn(&mut SchemaGenerator) -> schemars::Schema,
}

fn kind<T: JsonSchema>(key: &'static str, name: &'static str) -> Kind {
    Kind {
        key,
        name,
        register: SchemaGenerator::subschema_for::<T>,
    }
}

/// Every kind in the bundle, in output order. The engine kinds use the
/// names of `litigate_engine::api::SCHEMA_KINDS`.
fn kinds() -> Vec<Kind> {
    vec![
        kind::<Request>("request", "Request"),
        kind::<Response>("response", "Response"),
        kind::<Scenario>("scenario", "Scenario"),
        kind::<NamedScenario>("named-scenario", "NamedScenario"),
        kind::<Pack>("pack", "Pack"),
        kind::<LinkFile>("links", "LinkFile"),
        kind::<CalibrationSet>("calibration", "CalibrationSet"),
        kind::<ClockLibrary>("clock", "ClockLibrary"),
        kind::<Validation>("validation", "Validation"),
        kind::<Envelope<Value>>("litigate-envelope", "LitigateEnvelope"),
        kind::<LitigateRun>("litigate-run", "LitigateRun"),
        kind::<SourceMap>("source-map", "SourceMap"),
        kind::<Timeline>("timeline", "Timeline"),
    ]
}

/// The bundle.
///
/// # Panics
/// When a kind's published name is already taken by another definition,
/// or two distinct Rust types share a schema name (schemars would
/// otherwise silently suffix one of them).
#[must_use]
pub fn bundle() -> Value {
    let mut generator = SchemaGenerator::default();
    let mut properties = Map::new();
    let mut renames = Vec::new();
    let mut inline = Map::new();
    for k in kinds() {
        let schema = (k.register)(&mut generator).to_value();
        match schema["$ref"]
            .as_str()
            .and_then(|r| r.strip_prefix("#/$defs/"))
        {
            Some(name) if name != k.name => renames.push((name.to_owned(), k.name)),
            Some(_) => {}
            None => {
                inline.insert(k.name.to_owned(), schema);
            }
        }
        properties.insert(
            k.key.to_owned(),
            json!({ "$ref": format!("#/$defs/{}", k.name) }),
        );
    }
    let mut defs = generator.take_definitions(true);
    defs.extend(inline);
    let mut text = Value::Object(defs).to_string();
    for (from, to) in &renames {
        assert!(
            !text.contains(&format!("\"#/$defs/{to}\"")),
            "{to} is taken"
        );
        text = text.replace(&format!("\"#/$defs/{from}\""), &format!("\"#/$defs/{to}\""));
    }
    let mut defs: Map<String, Value> = serde_json::from_str(&text).unwrap_or_default();
    for (from, to) in renames {
        let schema = defs.remove(&from).unwrap_or_default();
        defs.insert(to.to_owned(), schema);
    }
    defs.sort_keys();
    let required: Vec<&str> = kinds().iter().map(|k| k.key).collect();
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "LitgraphSchemas",
        "description": "Every litgraph/litigate JSON document kind, keyed by kind. Generated by `cargo run -p litgraph-schema-bundle`; do not edit.",
        "type": "object",
        "properties": properties,
        "required": required,
        "additionalProperties": false,
        "$defs": defs,
    })
}

/// [`bundle`] as pretty JSON with a trailing newline.
#[must_use]
pub fn render() -> String {
    format!(
        "{}\n",
        serde_json::to_string_pretty(&bundle()).unwrap_or_default()
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_litgraph_schema_kind_is_bundled_as_published() {
        let b = bundle();
        for kind in litigate_engine::api::SCHEMA_KINDS {
            let name = b["properties"][kind]["$ref"]
                .as_str()
                .and_then(|r| r.strip_prefix("#/$defs/"))
                .unwrap_or_else(|| panic!("kind {kind} missing from the bundle"));
            let mut published = litigate_engine::api::schema(kind).unwrap();
            let published = published.as_object_mut().unwrap();
            published.remove("$schema");
            published.remove("$defs");
            published.remove("title");
            assert_eq!(
                &b["$defs"][name],
                &Value::Object(published.clone()),
                "{kind}"
            );
        }
    }

    #[test]
    fn refs_resolve_and_names_are_unsuffixed() {
        let b = bundle();
        let defs = b["$defs"].as_object().unwrap();
        let text = b.to_string();
        for r in text.split("\"#/$defs/").skip(1) {
            let name = &r[..r.find('"').unwrap()];
            assert!(defs.contains_key(name), "dangling $ref {name}");
        }
        let suffixed: Vec<&String> = defs
            .keys()
            .filter(|k| defs.contains_key(k.trim_end_matches(|c: char| c.is_ascii_digit())))
            .filter(|k| k.ends_with(|c: char| c.is_ascii_digit()))
            .collect();
        assert!(suffixed.is_empty(), "name clashes: {suffixed:?}");
        assert!(render().ends_with("}\n"));
    }
}
