//! The keyword table (`crates/litigate-syntax/keywords.txt`): the one
//! hand-edited list of contextual keywords. `build.rs` generates
//! [`SyntaxKind`](crate::SyntaxKind)'s keyword variants from it and
//! `litigate-editors` every editor keyword list, both through [`parse`].
//!
//! The file is shared with `build.rs` (`#[path]`), so it uses std only.

use std::fmt::Write as _;

/// The table's text as compiled into this crate.
pub const TABLE: &str = include_str!("../keywords.txt");

/// How editors highlight a keyword.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Highlight {
    /// Opens a declaration (`module`, `deadline`, `case`, ...).
    Declaration,
    /// A clause or field keyword (`by`, `within`, `counted_by`, ...).
    Clause,
    /// A test statement keyword (`given`, `expect`, `on`).
    Test,
    /// A conditional (`when`, `unless`, `otherwise`, `match`).
    Conditional,
    /// A directive (`cite`).
    Directive,
    /// Not in a keyword list: highlighted as a named node, or not at all.
    None,
}

impl Highlight {
    /// Every class, in the order editors list them.
    pub const ALL: [Highlight; 6] = [
        Highlight::Declaration,
        Highlight::Clause,
        Highlight::Test,
        Highlight::Conditional,
        Highlight::Directive,
        Highlight::None,
    ];

    /// The class's name in the table.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Highlight::Declaration => "declaration",
            Highlight::Clause => "clause",
            Highlight::Test => "test",
            Highlight::Conditional => "conditional",
            Highlight::Directive => "directive",
            Highlight::None => "none",
        }
    }
}

/// One row of the table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Keyword<'a> {
    /// `SyntaxKind` variant name, `Kw...`.
    pub variant: &'a str,
    /// Source spelling.
    pub text: &'a str,
    /// Editor highlight class.
    pub highlight: Highlight,
}

/// Parse the table: `Variant text highlight` per line, `#` comments and
/// blank lines skipped, rows in table order. An exact duplicate row (two
/// branches adding the same keyword, merged by `union`) is kept once.
///
/// # Errors
/// A malformed row, an unknown highlight class, or two different rows
/// sharing a variant or a spelling, as `line N: message`.
pub fn parse(table: &str) -> Result<Vec<Keyword<'_>>, String> {
    let mut rows: Vec<Keyword<'_>> = Vec::new();
    for (index, line) in table.lines().enumerate() {
        let line = line.split('#').next().unwrap_or_default();
        let fields: Vec<&str> = line.split_whitespace().collect();
        if fields.is_empty() {
            continue;
        }
        let at = |message: String| format!("line {}: {message}", index + 1);
        let [variant, text, highlight] = fields[..] else {
            return Err(at(format!(
                "expected `Variant text highlight`, found {} fields",
                fields.len()
            )));
        };
        let ident = |s: &str| {
            s.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
                && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        };
        if !(variant.starts_with("Kw") && ident(variant)) {
            return Err(at(format!("variant `{variant}` is not `Kw` + identifier")));
        }
        if !(ident(text) && text.chars().all(|c| c.is_ascii_alphabetic() || c == '_')) {
            return Err(at(format!("keyword `{text}` is not letters and `_`")));
        }
        let Some(highlight) = Highlight::ALL.into_iter().find(|h| h.name() == highlight) else {
            return Err(at(format!("unknown highlight `{highlight}`")));
        };
        let row = Keyword {
            variant,
            text,
            highlight,
        };
        if rows.contains(&row) {
            continue;
        }
        if let Some(other) = rows
            .iter()
            .find(|other| other.variant == variant || other.text == text)
        {
            return Err(at(format!(
                "`{variant} {text}` clashes with `{} {}`",
                other.variant, other.text
            )));
        }
        rows.push(row);
    }
    Ok(rows)
}

/// The `syntax_kinds_with_keywords!` macro `build.rs` writes: it forwards
/// its `tokens`, `punct` and `nodes` groups to `syntax_kinds!` with the
/// table's `keywords` group between them.
#[must_use]
pub fn rust_macro(rows: &[Keyword<'_>]) -> String {
    let mut out = String::from(
        "// Generated by crates/litigate-syntax/build.rs from keywords.txt.\n\
         macro_rules! syntax_kinds_with_keywords {\n    \
         (tokens $tokens:tt punct $punct:tt nodes $nodes:tt) => {\n        \
         syntax_kinds! {\n            tokens $tokens\n            punct $punct\n            \
         keywords {\n",
    );
    for row in rows {
        let _ = writeln!(out, "                {} = {:?},", row.variant, row.text);
    }
    out.push_str("            }\n            nodes $nodes\n        }\n    };\n}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::{parse, Highlight, TABLE};

    #[test]
    fn the_table_parses() {
        let rows = parse(TABLE).unwrap_or_default();
        assert!(rows.iter().any(|row| row.text == "module"
            && row.variant == "KwModule"
            && row.highlight == Highlight::Declaration));
    }

    #[test]
    fn an_exact_duplicate_is_kept_once() {
        let rows = parse("KwA a clause\n# note\n\nKwA a clause  # again\n");
        assert_eq!(rows.map(|rows| rows.len()), Ok(1));
    }

    #[test]
    fn clashing_and_malformed_rows_are_errors() {
        for (table, message) in [
            (
                "KwA a clause\nKwA b clause\n",
                "line 2: `KwA b` clashes with `KwA a`",
            ),
            (
                "KwA a clause\nKwB a test\n",
                "line 2: `KwB a` clashes with `KwA a`",
            ),
            (
                "KwA a clause\nKwA a test\n",
                "line 2: `KwA a` clashes with `KwA a`",
            ),
            (
                "KwA a\n",
                "line 1: expected `Variant text highlight`, found 2 fields",
            ),
            (
                "A a clause\n",
                "line 1: variant `A` is not `Kw` + identifier",
            ),
            (
                "KwA a-b clause\n",
                "line 1: keyword `a-b` is not letters and `_`",
            ),
            ("KwA a bold\n", "line 1: unknown highlight `bold`"),
        ] {
            assert_eq!(parse(table), Err(message.to_owned()), "{table}");
        }
    }
}
