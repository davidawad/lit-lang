//! Build the repository's generated packs, `links.json`, generated clock
//! fragments and named scenarios from `lit/` and `cases/` (the arguments in
//! `build.args`), through the same `litigate build` the CLI runs, over an
//! in-memory copy of the sources. The output lands in `OUT_DIR/packs` and
//! `OUT_DIR/scenarios` (with the hand-authored `packs/clock/*.json` copied
//! beside the generated fragments) and is embedded. Nothing generated is
//! committed, so parallel `lit/` changes never conflict on it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default());
    let repo = manifest.join("../..");

    let args = build_args(&manifest.join("build.args"));
    let mut sources = BTreeMap::new();
    for dir in ["lit", "cases"] {
        collect(&repo, &repo.join(dir), &mut sources);
    }
    let run = litigate_cli::execute_in_memory(sources, &args);
    assert!(
        run.code == 0,
        "`litigate {}` failed (exit {}); fix lit/ or cases/ (after a merge, \
         `just lit-sync` regenerates the Lit.lock files):\n{}{}",
        args.join(" "),
        run.code,
        run.stdout,
        run.stderr
    );
    let packs = out_dir.join("packs");
    let scenarios = out_dir.join("scenarios");
    lay_out(&run.files, &repo.join("packs/clock"), &out_dir);

    let mut src = String::new();
    embed(
        &mut src,
        "PACKS",
        "`(file name, contents)` of every built pack, `links.json` and `clock/` fragment (generated and hand-authored).",
        &[(&packs, ""), (&packs.join("clock"), "clock/")],
    );
    embed(
        &mut src,
        "SCENARIOS",
        "`(file name, contents)` of every built named scenario.",
        &[(&scenarios, "")],
    );
    let _ = writeln!(
        src,
        "/// The directory holding the built packs (`clock/` included).\npub const PACKS_DIR: &str = {:?};",
        packs.display().to_string()
    );
    let _ = writeln!(
        src,
        "/// The directory holding the built named scenarios.\npub const SCENARIOS_DIR: &str = {:?};",
        scenarios.display().to_string()
    );
    write(&out_dir.join("embedded.rs"), &src);
}

/// `--format human build <build.args> --out out`.
fn build_args(file: &Path) -> Vec<String> {
    println!("cargo:rerun-if-changed={}", file.display());
    let mut args: Vec<String> = ["--format", "human", "build"].map(str::to_owned).into();
    args.extend(
        read(file)
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_owned),
    );
    args.extend(["--out", "out"].map(str::to_owned));
    args
}

/// Write the build's `out/packs/**.json` and `out/scenarios/*.json` (source
/// maps aside) under `out_dir`, then copy the hand-authored clock library
/// from `clock` beside the generated fragments, so `PACKS` (and
/// `PACKS_DIR/clock`) is the complete clock library a catalog needs.
fn lay_out(files: &BTreeMap<String, String>, clock: &Path, out_dir: &Path) {
    let packs = out_dir.join("packs");
    for dir in [&packs, &out_dir.join("scenarios")] {
        // A stale file from an earlier build must not survive a removal.
        let _ = std::fs::remove_dir_all(dir);
        mkdir(dir);
    }
    mkdir(&packs.join("clock"));
    for (path, text) in files {
        let Some(rel) = path.strip_prefix("out/") else {
            continue;
        };
        let generated = rel.starts_with("packs/") || rel.starts_with("scenarios/");
        if generated && !rel.ends_with(".map.json") {
            write(&out_dir.join(rel), text);
        }
    }
    println!("cargo:rerun-if-changed={}", clock.display());
    for path in json_files(clock) {
        let target = packs
            .join("clock")
            .join(path.file_name().unwrap_or_default());
        assert!(
            !target.exists(),
            "{} is both hand-authored and generated by lit/",
            target.display()
        );
        write(&target, &read(&path));
    }
}

/// `pub static <ident>: &[(&str, &str)]` over every `*.json` directly in
/// each `(dir, key prefix)`, in key order.
fn embed(src: &mut String, ident: &str, doc: &str, dirs: &[(&Path, &str)]) {
    let mut entries: Vec<(String, PathBuf)> = dirs
        .iter()
        .flat_map(|(dir, prefix)| {
            json_files(dir).into_iter().map(move |p| {
                let name = p.file_name().and_then(|n| n.to_str()).unwrap_or_default();
                (format!("{prefix}{name}"), p.clone())
            })
        })
        .collect();
    entries.sort();
    let _ = writeln!(src, "/// {doc}\npub static {ident}: &[(&str, &str)] = &[");
    for (key, path) in entries {
        let _ = writeln!(
            src,
            "    ({key:?}, include_str!({:?})),",
            path.display().to_string()
        );
    }
    src.push_str("];\n");
}

/// Every `*.json` file directly in `dir`, sorted.
fn json_files(dir: &Path) -> Vec<PathBuf> {
    let read = std::fs::read_dir(dir).unwrap_or_else(|e| {
        panic!(
            "{} is missing ({e}); it must be in the build context",
            dir.display()
        )
    });
    let mut files: Vec<PathBuf> = read
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    files
}

/// Every file under `dir` (hidden entries skipped), keyed by its path
/// relative to `repo` with `/` separators, as `litigate build` sees it run
/// from the repository root.
fn collect(repo: &Path, dir: &Path, out: &mut BTreeMap<String, String>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let read = std::fs::read_dir(dir).unwrap_or_else(|e| {
        panic!(
            "{} is missing ({e}); it must be in the build context",
            dir.display()
        )
    });
    for path in read.filter_map(|e| e.ok().map(|e| e.path())) {
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(repo, &path, out);
        } else if let Ok(text) = std::fs::read_to_string(&path) {
            let rel = path.strip_prefix(repo).unwrap_or(&path);
            out.insert(rel.to_string_lossy().replace('\\', "/"), text);
        }
    }
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()))
}

fn mkdir(dir: &Path) {
    std::fs::create_dir_all(dir).unwrap_or_else(|e| panic!("creating {}: {e}", dir.display()));
}

fn write(path: &Path, text: &str) {
    if let Some(parent) = path.parent() {
        mkdir(parent);
    }
    std::fs::write(path, text).unwrap_or_else(|e| panic!("writing {}: {e}", path.display()));
}
