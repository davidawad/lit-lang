// Generates src/generated/schemas.ts from schema/litgraph.schema.json, the
// JSON Schema bundle `cargo run -p litgraph-schema-bundle` emits from the
// Rust types. Run through `just ts-gen`; never edit the output by hand.
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const root = new URL("../", import.meta.url);
const bundle = JSON.parse(await readFile(new URL("schema/litgraph.schema.json", root), "utf8"));

// Keywords whose value is one subschema, an array of them, or a map of them.
const one = ["additionalProperties", "items", "not", "if", "then", "else", "contains", "propertyNames"];
const many = ["allOf", "anyOf", "oneOf", "prefixItems"];
const named = ["properties", "patternProperties", "$defs", "dependentSchemas"];
const annotations = new Set(["description", "default", "title", "examples", "deprecated"]);
const mapValues = (o, f) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, f(v)]));

// Two fixes to schemars output before json-schema-to-typescript sees it:
// - a schema with only annotations (`serde_json::Value`) accepts any JSON
//   value; the compiler would guess `{[k: string]: unknown}`, so pin it to
//   `unknown`.
// - schemars puts a field's doc (and default) beside its `$ref`; the ref
//   parser then copies the referenced schema per use site, which surfaces
//   as duplicate `Span1`, `Op1`, ... types. A one-element `allOf` keeps the
//   field doc and points every use at the one named type.
function normalize(schema) {
  if (schema === null || typeof schema !== "object" || Array.isArray(schema)) return schema;
  const out = { ...schema };
  for (const k of one) if (k in out) out[k] = normalize(out[k]);
  for (const k of many) if (Array.isArray(out[k])) out[k] = out[k].map(normalize);
  for (const k of named) if (k in out) out[k] = mapValues(out[k], normalize);
  const keys = Object.keys(out);
  if (keys.every((k) => annotations.has(k))) return { ...out, tsType: "unknown" };
  if ("$ref" in out && keys.length > 1 && keys.every((k) => k === "$ref" || annotations.has(k))) {
    const { $ref, ...rest } = out;
    return { ...rest, allOf: [{ $ref }] };
  }
  return out;
}

const banner = `// SPDX-License-Identifier: GPL-3.0-or-later
// GENERATED by \`just ts-gen\` from the Rust schemas (crates/litgraph-schema-bundle).
// Do not edit: change the Rust type, then regenerate. CI (\`just ts-gen-check\`)
// fails when this file is stale.
`;

const ts = await compile(normalize(bundle), "LitgraphSchemas", {
  bannerComment: banner,
  // Every definition is reachable from the root's kind properties.
  declareExternallyReferenced: true,
  // Free-form JSON is `unknown`, never `any`.
  unknownAny: true,
  strictIndexSignatures: true,
  additionalProperties: false,
  format: true,
  style: { singleQuote: false, trailingComma: "all", printWidth: 100 },
});

await writeFile(new URL("src/generated/schemas.ts", root), ts);
