//! tree-sitter grammar for litigate: `.lit` rule modules and `.case`
//! matters share one grammar whose root `source_file` holds either a
//! `lit_file` or a `case_file`.
//!
//! ```
//! let mut parser = tree_sitter::Parser::new();
//! parser
//!     .set_language(&tree_sitter_litigate::LANGUAGE.into())
//!     .expect("the litigate grammar loads");
//! let tree = parser.parse("module frcp.rule12\nstart s\n", None).expect("parses");
//! assert!(!tree.root_node().has_error());
//! ```
//!
//! The compiler's hand-written parser (`litigate-syntax`) is the source of
//! truth for syntax; this grammar is the editor view of the same language
//! and the crate's conformance test keeps the two in step.

use tree_sitter_language::LanguageFn;

extern "C" {
    fn tree_sitter_litigate() -> *const ();
}

/// The tree-sitter [`LanguageFn`] for litigate.
#[allow(unsafe_code)]
// SAFETY: `tree_sitter_litigate` is the parser entry point generated by
// `tree-sitter generate` into src/parser.c and compiled by build.rs; it
// returns a pointer to a static `TSLanguage` with the ABI the CLI emitted.
pub const LANGUAGE: LanguageFn = unsafe { LanguageFn::from_raw(tree_sitter_litigate) };

/// Contents of `src/node-types.json`: every named node and its fields.
pub const NODE_TYPES: &str = include_str!("../../src/node-types.json");

/// Syntax highlighting query.
pub const HIGHLIGHTS_QUERY: &str = include_str!("../../queries/highlights.scm");

/// Scope, definition and reference query.
pub const LOCALS_QUERY: &str = include_str!("../../queries/locals.scm");

/// Language injection query (litigate embeds no other language).
pub const INJECTIONS_QUERY: &str = include_str!("../../queries/injections.scm");

/// Code folding query.
pub const FOLDS_QUERY: &str = include_str!("../../queries/folds.scm");

/// Indentation query.
pub const INDENTS_QUERY: &str = include_str!("../../queries/indents.scm");

#[cfg(test)]
mod tests {
    use super::{
        FOLDS_QUERY, HIGHLIGHTS_QUERY, INDENTS_QUERY, INJECTIONS_QUERY, LANGUAGE, LOCALS_QUERY,
    };

    #[test]
    fn language_loads() {
        let mut parser = tree_sitter::Parser::new();
        assert!(parser.set_language(&LANGUAGE.into()).is_ok());
    }

    #[test]
    fn every_query_compiles() {
        let language = LANGUAGE.into();
        for (name, source) in [
            ("highlights", HIGHLIGHTS_QUERY),
            ("locals", LOCALS_QUERY),
            ("injections", INJECTIONS_QUERY),
            ("folds", FOLDS_QUERY),
            ("indents", INDENTS_QUERY),
        ] {
            let query = tree_sitter::Query::new(&language, source);
            assert!(query.is_ok(), "{name}.scm: {:?}", query.err());
        }
    }
}
